def generate_review_html(review_data: dict, pr_data: dict) -> str:
    score = review_data.get("overall_score") or 0
    score_color = "#22c55e" if score >= 7 else "#f59e0b" if score >= 5 else "#ef4444"

    template = Template(HTML_TEMPLATE)
    return template.render(
        pr_title=pr_data.get("title", "Pull Request"),
        pr_number=pr_data.get("number", ""),
        repo_name=pr_data.get("repo_name", ""),
        author=pr_data.get("author", ""),
        date=datetime.utcnow().strftime("%B %d, %Y"),
        score=f"{score:.1f}",
        score_color=score_color,
        summary=review_data.get("summary", ""),
        issues=review_data.get("issues", []),
        suggestions=review_data.get("suggestions", []),
        security_flags=review_data.get("security_flags", []),
        metrics=review_data.get("metrics", {}),
        model_used=review_data.get("model_used", "groq"),
    )


def generate_pdf_bytes(html: str) -> bytes:
    """Convert HTML to PDF using WeasyPrint."""
    try:
        from weasyprint import HTML
        return HTML(string=html).write_pdf()
    except ImportError:
        # Fallback: return HTML as bytes if weasyprint unavailable
        return html.encode("utf-8")


def upload_to_s3(pdf_bytes: bytes, key: str) -> Optional[str]:
    """Upload PDF to S3 and return the URL."""
    if not settings.aws_s3_bucket or not settings.aws_access_key_id:
        return None
    try:
        s3 = boto3.client(
            "s3",
            aws_access_key_id=settings.aws_access_key_id,
            aws_secret_access_key=settings.aws_secret_access_key,
            region_name=settings.aws_region,
        )
        s3.put_object(
            Bucket=settings.aws_s3_bucket,
            Key=key,
            Body=pdf_bytes,
            ContentType="application/pdf",
        )
        return f"https://{settings.aws_s3_bucket}.s3.{settings.aws_region}.amazonaws.com/{key}"
    except Exception as e:
        print(f"S3 upload failed: {e}")
        return None
